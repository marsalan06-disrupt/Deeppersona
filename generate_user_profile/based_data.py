def generate_location(country_code: str = None) -> Dict[str, str]:
    """
    Generate geographic location information for a random city.

    Args:
        country_code: Optional ISO country code (e.g., "US", "GB", "IN").
                      If not provided, randomly selects from diverse countries.

    Returns:
        Dict[str, str]:
            - country: Country name
            - city: Random city name from that country
    """
    gc = GeonamesCache()
    countries = gc.get_countries()

    # If no country specified, randomly select from diverse list
    if not country_code:
        diverse_countries = ["US", "GB", "CA", "AU", "DE", "FR", "IN", "JP", "BR", "SG"]
        country_code = random.choice(diverse_countries)

    # Validate country code exists
    if country_code not in countries:
        print(f"Warning: Country code '{country_code}' not found, defaulting to US")
        country_code = "US"

    country = countries[country_code]

    # Filter all cities for selected country
    cities = gc.get_cities()
    country_cities_list = [
        city for city in cities.values()
        if city["countrycode"] == country_code
    ]

    # Fallback if no cities found
    if not country_cities_list:
        fallback_cities = {
            "US": "New York", "GB": "London", "CA": "Toronto", "AU": "Sydney",
            "DE": "Berlin", "FR": "Paris", "IN": "Mumbai", "JP": "Tokyo",
            "BR": "São Paulo", "SG": "Singapore"
        }
        return {"country": country["name"], "city": fallback_cities.get(country_code, "Unknown")}

    # Randomly select a city
    city_data = random.choice(country_cities_list)
    return {"country": country["name"], "city": city_data["name"]}


