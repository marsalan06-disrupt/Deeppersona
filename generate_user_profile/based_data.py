_occupations_cache = None

def get_occupations() -> List[str]:
    """Get occupation data from local file.

    Read occupation list from predefined JSON file. Uses caching to avoid repeated file reads.
    Returns empty list if file read fails.

    Returns:
        List[str]: Occupation list. Returns empty list if retrieval fails
    """
    global _occupations_cache

    if _occupations_cache is not None:
        return _occupations_cache

    try:
        # Use data folder under project root directory
        project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
        file_path = os.path.join(project_root, 'data', 'occupations_english.json')
        with open(file_path, 'r', encoding='utf-8') as f:
            _occupations_cache = json.load(f)
        return _occupations_cache
    except Exception as e:
        print(f"Error loading occupations data: {e}")
        return []

def generate_age_info() -> Dict[str, Union[int, str]]:
    """Generate age information.

    First randomly generate an age in the 7-85 range, then determine the corresponding age group.
    Age groups include: toddler, child, adolescent, young_adult, adult, middle_aged, senior.

    Returns:
        Dict[str, Union[int, str]]: Dictionary containing:
            - age: Specific age (integer)
            - age_group: Age group category
    """
    # First randomly generate age
    age = random.randint(7, 85)

    # Determine age group based on age
    if age <= 6:
        age_group = "toddler"
    elif age <= 12:
        age_group = "child"
    elif age <= 19:
        age_group = "adolescent"
    elif age <= 29:
        age_group = "young_adult"
    elif age <= 45:
        age_group = "adult"
    elif age <= 65:
        age_group = "middle_aged"
    else:
        age_group = "senior"

    return {
        "age": age,
        "age_group": age_group
    }

def generate_career_info(age: int) -> Dict[str, str]:
    """Generate career-related information.

    Determine career generation method based on age:
    - For people under 18 or over 65, career status is generated by GPT based on age
    - For other age groups, randomly select from local occupation database

    Args:
        age: Age

    Returns:
        Dict[str, str]: Career-related information containing occupation status
    """
    if age < 18 or age > 65:
        # For under 18 or over 65, career status is generated by GPT
        prompt = f"Generate an appropriate occupation or status for a {age} year old person. "
        if age < 18:
            prompt += "Consider that the individuals are likely in school or engaged in youth activities. They may not have any formal occupation. If appropriate, you can mention their student status or indicate they have no occupation yet. Only in some cases, consider potential interest in early employment opportunities, internships, or non-traditional educational paths."
        else:  # age > 65
            prompt += "Consider they might be retired but could still be active in various ways."

        messages = [
            {"role": "system", "content": "You are an AI that generates realistic occupation statuses based on age. Respond with just the status, no explanation."},
            {"role": "user", "content": prompt}
        ]

        status = get_completion(messages)
        if not status:
            return {"status": ""}
        return {"status": status}

    # Other age groups select from occupation database
    occupations = get_occupations()
    if not occupations:
        return {"status": ""}

    career_status = random.choice(occupations)
    return {"status": career_status}

